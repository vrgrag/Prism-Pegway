// --- Compact authoring helpers -------------------------------------------------

GameObject _c(double x, double y, {int v = 0}) =>
    GameObject(type: ObjectType.crystal, x: x, y: y, variant: v);

GameObject _peg(double x, double y, {int v = 0}) =>
    GameObject(type: ObjectType.peg, x: x, y: y, variant: v);

GameObject _wall(double x, double y, double hw, double hh) => GameObject(
  type: ObjectType.wall,
  x: x,
  y: y,
  halfWidth: hw,
  halfHeight: hh,
);

GameObject _magnet(double x, double y, {int v = 0}) =>
    GameObject(type: ObjectType.magnet, x: x, y: y, variant: v);

GameObject _tp(double x, double y, int link, {int v = 0}) =>
    GameObject(type: ObjectType.teleporter, x: x, y: y, link: link, variant: v);

GameObject _prism(double x, double y, double angle, {int v = 0}) =>
    GameObject(type: ObjectType.prism, x: x, y: y, angle: angle, variant: v);

Map<ObjectType, int> _inv({
  int peg = 0,
  int booster = 0,
  int spring = 0,
  int magnet = 0,
  int prism = 0,
  int teleporter = 0,
}) {
  final m = <ObjectType, int>{};
  if (peg > 0) m[ObjectType.peg] = peg;
  if (booster > 0) m[ObjectType.booster] = booster;
  if (spring > 0) m[ObjectType.spring] = spring;
  if (magnet > 0) m[ObjectType.magnet] = magnet;
  if (prism > 0) m[ObjectType.prism] = prism;
  if (teleporter > 0) m[ObjectType.teleporter] = teleporter;
  return m;
}

